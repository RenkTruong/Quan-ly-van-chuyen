// Helper tạo phân quyền chuẩn theo vai trò
export const createDefaultPermissions = (role: 'admin' | 'editor' | 'viewer' | 'blocked'): Record<AppPermissionModule, ModulePermission> => {
  const isBlocked = role === 'blocked';
  const isAdmin = role === 'admin';
  const isEditor = role === 'editor';
  
  const modules: AppPermissionModule[] = [
    'dashboard', 'price_customer', 'price_vendor', 'vendors', 'operations', 'reports', 'users', 'audit'
  ];

  const perms: Record<AppPermissionModule, ModulePermission> = {} as any;
  modules.forEach((m) => {
    if (isBlocked) {
      perms[m] = { blocked: true, view: false, edit: false, add: false };
    } else if (isAdmin) {
      perms[m] = { blocked: false, view: true, edit: true, add: true };
    } else if (isEditor) {
      const isRestricted = m === 'users' || m === 'audit';
      perms[m] = {
        blocked: isRestricted,
        view: !isRestricted,
        edit: !isRestricted,
        add: !isRestricted,
      };
    } else {
      // viewer
      const isRestricted = m === 'users' || m === 'audit';
      perms[m] = {
        blocked: isRestricted,
        view: !isRestricted,
        edit: false,
        add: false,
      };
    }
  });
  return perms;
};

